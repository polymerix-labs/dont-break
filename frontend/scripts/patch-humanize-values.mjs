function entryRegex(key) {
    const k = key.replace(/\./g, "\\.");
    return new RegExp(`"${k}":\\s*\\n?\\s*"(?:[^"\\\\]|\\\\.)*",`);
}
for (const file of readdirSync(localesDir)) {
    if (!file.endsWith(".ts") || file === "en.ts")
        continue;
    const code = file.replace(".ts", "");
    const path = join(localesDir, file);
    let content = readFileSync(path, "utf8");
    const dict = T[code];
    if (!dict) {
        console.error(`missing translations for ${code}`);
        process.exitCode = 1;
        continue;
    }
    let changed = 0;
    for (const [key, value] of Object.entries(dict)) {
        const re = entryRegex(key);
        if (!re.test(content)) {
            console.error(`entry ${key} not found in ${code}`);
            process.exitCode = 1;
            continue;
        }
        content = content.replace(re, `${JSON.stringify(key)}: ${JSON.stringify(value)},`);
        changed += 1;
    }
    writeFileSync(path, content);
    console.log(`patched ${code} (${changed})`);
}
